// scripts/build-blog-index.mjs
// Parse les fichiers Markdown de src/content/blog/ et génère
// src/app/data/blog-index.generated.ts avec les articles déjà rendus.
// Exécuté avant chaque build. Aucune dépendance markdown au runtime client.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import { marked } from 'marked';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const BLOG_DIR = path.join(ROOT, 'src/content/blog');
const OUT = path.join(ROOT, 'src/app/data/blog-index.generated.ts');

marked.use({ gfm: true, breaks: false });

if (!fs.existsSync(BLOG_DIR)) {
  fs.mkdirSync(BLOG_DIR, { recursive: true });
}

const files = fs
  .readdirSync(BLOG_DIR)
  .filter((f) => f.endsWith('.md'))
  .sort();

const posts = files.map((file) => {
  const raw = fs.readFileSync(path.join(BLOG_DIR, file), 'utf-8');
  const { data, content } = matter(raw);

  // Validation minimale
  const required = ['title', 'slug', 'description', 'date'];
  for (const key of required) {
    if (!data[key]) {
      throw new Error(`[blog-index] "${file}" : front-matter "${key}" manquant`);
    }
  }

  const expectedSlug = file.replace(/\.md$/, '');
  if (data.slug !== expectedSlug) {
    throw new Error(
      `[blog-index] "${file}" : slug du front-matter ("${data.slug}") différent du nom de fichier ("${expectedSlug}")`,
    );
  }

  const html = marked.parse(content);

  return {
    slug: data.slug,
    frontmatter: {
      title: data.title,
      slug: data.slug,
      description: data.description,
      date: data.date,
      author: data.author ?? 'MARVHL',
      category: data.category ?? 'Guide',
      tags: Array.isArray(data.tags) ? data.tags : [],
      reading_time: typeof data.reading_time === 'number' ? data.reading_time : 5,
      og_image: data.og_image ?? '/og-image.jpg',
    },
    html,
  };
});

// Tri par date décroissante (plus récent en premier)
posts.sort((a, b) => b.frontmatter.date.localeCompare(a.frontmatter.date));

const header = `// AUTO-GENERATED by scripts/build-blog-index.mjs
// DO NOT EDIT — regenerate via "npm run blog-index" ou "npm run build".

export interface BlogFrontmatter {
  title: string;
  slug: string;
  description: string;
  date: string; // ISO (YYYY-MM-DD)
  author: string;
  category: string;
  tags: string[];
  reading_time: number;
  og_image: string;
}

export interface BlogPost {
  slug: string;
  frontmatter: BlogFrontmatter;
  html: string;
}

export const blogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(OUT, header, 'utf-8');
console.log(`✓ blog-index.generated.ts : ${posts.length} article${posts.length > 1 ? 's' : ''} indexé${posts.length > 1 ? 's' : ''}`);
